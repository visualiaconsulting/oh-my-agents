"""Native Codex TOML rendering; no OpenCode provider settings are copied."""
import json

import tomlkit

from agent_catalog import SPECIALISTS, instructions_for

START = "<!-- oh-my-agents:begin -->"
END = "<!-- oh-my-agents:end -->"


def _instructions(existing: str) -> str:
    block = START + "\n" + instructions_for("orchestrator").rstrip() + "\n" + END
    if START in existing or END in existing:
        if existing.count(START) != 1 or existing.count(END) != 1 or existing.index(START) > existing.index(END):
            raise ValueError("Malformed oh-my-agents instructions block")
        prefix, rest = existing.split(START, 1)
        _, suffix = rest.split(END, 1)
        return prefix + block + suffix
    return (existing.rstrip() + "\n\n" if existing.strip() else "") + block + "\n"


def render_files(root, catalog, profile):
    path = root / ".codex" / "config.toml"
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    doc = tomlkit.parse(existing)
    primary = profile["models"]["orchestrator"]
    doc["model"] = primary["model"]
    doc["model_reasoning_effort"] = primary["reasoning_effort"]
    if "agents" not in doc:
        doc["agents"] = tomlkit.table()
    if not isinstance(doc["agents"], dict):
        raise ValueError("Existing Codex agents setting must be a TOML table")
    compatibility = profile.get("codex_compat", "modern")
    if compatibility not in ("modern", "legacy"):
        raise ValueError("codex_compat must be modern or legacy")
    if compatibility == "legacy":
        doc["agents"].pop("enabled", None)
        doc["agents"].pop("max_concurrent_threads_per_session", None)
        doc["agents"]["max_threads"] = profile["max_concurrent_specialists"]
        if "features" not in doc:
            doc["features"] = tomlkit.table()
        if not isinstance(doc["features"], dict):
            raise ValueError("Existing Codex features setting must be a TOML table")
        doc["features"]["multi_agent"] = True
    else:
        doc["agents"]["enabled"] = True
        # max_threads is a legacy alias; never emit both concurrency keys.
        doc["agents"].pop("max_threads", None)
        doc["agents"]["max_concurrent_threads_per_session"] = profile["max_concurrent_specialists"]
        # Remove only the equivalent flag written by our previous legacy export.
        features = doc.get("features")
        if profile.get("previous_codex_compat") == "legacy" and isinstance(features, dict):
            if features.get("multi_agent") is True:
                features.pop("multi_agent")
            if not features:
                doc.pop("features")
    for role in SPECIALISTS:
        expected = f"agents/{role}.toml"
        if role in doc["agents"]:
            existing_role = doc["agents"][role]
            if not isinstance(existing_role, dict) or existing_role.get("config_file") != expected:
                raise ValueError(f"Custom Codex registration conflicts with role: {role}")
        else:
            doc["agents"][role] = tomlkit.table()
        doc["agents"][role]["description"] = catalog["roles"][role]["description"]
        doc["agents"][role]["config_file"] = expected
    result = {".codex/config.toml": tomlkit.dumps(doc)}
    for role in SPECIALISTS:
        settings = profile["models"][role]
        result[f".codex/agents/{role}.toml"] = (
            "# Generated by oh-my-agents. Customize the catalog/prompt source, then export.\n"
            f"name = {json.dumps(role)}\n"
            f"description = {json.dumps(catalog['roles'][role]['description'])}\n"
            f"model = {json.dumps(settings['model'])}\n"
            f"model_reasoning_effort = {json.dumps(settings['reasoning_effort'])}\n"
            f"developer_instructions = {json.dumps(instructions_for(role))}\n"
        )
    # Windows is case-insensitive; reuse a legacy agents.md instead of making a
    # second file which would conflict on checkout on Windows.
    instruction_path = next((p for p in root.glob("*") if p.name.lower() == "agents.md"), root / "AGENTS.md")
    content = instruction_path.read_text(encoding="utf-8") if instruction_path.exists() else ""
    result[instruction_path.name] = _instructions(content)
    return result


def configuration_warnings(root):
    path = root / ".codex/config.toml"
    if not path.exists():
        return []
    agents = tomlkit.parse(path.read_text(encoding="utf-8")).get("agents", {})
    return [f"Preserved custom Codex agent registration outside the five-role catalog: {name}"
            for name, value in agents.items() if isinstance(value, dict) and name not in SPECIALISTS]
